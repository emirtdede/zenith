/**
 * Translated chrome for languages without a full catalogue.
 *
 * A menu that says "Ayarlar" over English prose is a worse experience than an
 * honest English menu, so this layer is deliberately narrow: the words a user
 * must recognise to reach the setting that changes the language, plus the
 * navigation and window controls. Everything longer falls back to English and
 * Settings > Language says so before the choice is made.
 *
 * Only languages whose Windows install base justifies a reviewed chrome layer
 * are listed. The picker still offers all 73: choosing one that is absent here
 * keeps the window in English while dates, numbers and collation follow the
 * chosen locale - the one part of localisation a catalogue is not needed for.
 */
