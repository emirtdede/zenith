//! Renderer for `src/catalog.generated.ts`.
//!
//! The manifest is the single source of truth (ADR-011). The webview needs the
//! same rows the core enforces, and a hand-maintained copy is exactly how v1.0.0
//! drifted. This module is the *only* implementation of the conversion: the
//! `dump_manifest` example prints it, and the `catalog_in_sync` integration test
//! compares the committed file against it. A stale file therefore fails a test
//! rather than a user.

use crate::manifest::{self, ActionScope, CommandSpec};

/// Render the complete TypeScript module.
pub fn render() -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo run -p zenith-core --example dump_manifest`.\n");
    out.push_str(
        "// Do not edit: `cargo test -p zenith-core --test catalog_in_sync` fails on drift.\n",
    );
    out.push_str("/* eslint-disable */\n\n");

    // Every line but the last is terminated by a newline alone. A trailing `|`
    // before the semicolon is not valid TypeScript.
    out.push_str("export type ActionId =\n");
    for (index, def) in manifest::ACTIONS.iter().enumerate() {
        let terminator = if index + 1 == manifest::ACTIONS.len() {
            ";"
        } else {
            ""
        };
        out.push_str(&format!("  | '{}'{terminator}\n", def.id.as_str()));
    }

    out.push_str("\nexport interface ActionDef {\n");
    out.push_str("  readonly id: ActionId;\n");
    out.push_str("  readonly order: number;\n");
    out.push_str("  readonly category: 'cleanup' | 'network' | 'recovery' | 'dev_office';\n");
    out.push_str("  readonly risk: 'safe' | 'moderate' | 'destructive';\n");
    out.push_str(
        "  readonly tier: 'fully_reversible' | 'partially_reversible' | 'compensating_recovery' | 'irreversible';\n",
    );
    out.push_str("  readonly requiresAdmin: boolean;\n");
    out.push_str("  readonly safeBatch: boolean;\n");
    out.push_str("  readonly abortable: boolean;\n");
    out.push_str("  readonly noMutation: boolean;\n");
    out.push_str("  readonly readOnly: boolean;\n");
    out.push_str("  readonly dependsOn: readonly ActionId[];\n");
    out.push_str("  readonly timeoutSecs: number;\n");
    out.push_str("  readonly severityWeight: 1 | 2 | 3;\n");
    out.push_str(
        "  readonly scope: 'temp_dirs' | 'recycle_bin' | 'screenshots' | 'icon_cache' | 'spooler' | 'office_cache' | 'internet_settings' | 'winsock' | 'services_only' | 'explorer_session' | 'none';\n",
    );
    out.push_str("  readonly diagnoseBudgetMs: number;\n");
    out.push_str("  readonly i18nPrefix: string;\n");
    out.push_str("  readonly ps1: string;\n");
    out.push_str("  readonly bat: string;\n");
    out.push_str("}\n\n");

    out.push_str("export const ACTIONS: readonly ActionDef[] = [\n");
    for def in manifest::ACTIONS {
        let depends = def
            .depends_on
            .iter()
            .map(|id| format!("'{}'", id.as_str()))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str("  {\n");
        out.push_str(&format!("    id: '{}',\n", def.id.as_str()));
        out.push_str(&format!("    order: {},\n", def.order));
        out.push_str(&format!("    category: '{}',\n", def.category.as_str()));
        out.push_str(&format!("    risk: '{}',\n", def.risk.as_str()));
        out.push_str(&format!("    tier: '{}',\n", def.tier.as_str()));
        out.push_str(&format!("    requiresAdmin: {},\n", def.requires_admin));
        out.push_str(&format!("    safeBatch: {},\n", def.safe_batch));
        out.push_str(&format!("    abortable: {},\n", def.abortable));
        out.push_str(&format!("    noMutation: {},\n", def.no_mutation));
        out.push_str(&format!("    readOnly: {},\n", def.read_only));
        out.push_str(&format!("    dependsOn: [{depends}],\n"));
        out.push_str(&format!("    timeoutSecs: {},\n", def.timeout_secs));
        out.push_str(&format!("    severityWeight: {},\n", def.severity_weight));
        out.push_str(&format!("    scope: '{}',\n", def.scope.as_str()));
        out.push_str(&format!(
            "    diagnoseBudgetMs: {},\n",
            def.diagnose_budget_ms
        ));
        out.push_str(&format!("    i18nPrefix: '{}',\n", def.i18n_prefix));
        out.push_str(&format!("    ps1: {},\n", template(def.ps1)));
        out.push_str(&format!("    bat: {},\n", template(def.bat)));
        out.push_str("  },\n");
    }
    out.push_str("];\n\n");

    out.push_str("export const SAFE_PRESET: readonly ActionId[] = [\n");
    for id in manifest::SAFE_PRESET {
        out.push_str(&format!("  '{}',\n", id.as_str()));
    }
    out.push_str("];\n\n");

    out.push_str("export const ADMIN_ACTIONS: readonly ActionId[] = [\n");
    for def in manifest::ACTIONS.iter().filter(|def| def.requires_admin) {
        out.push_str(&format!("  '{}',\n", def.id.as_str()));
    }
    out.push_str("];\n\n");

    // Command specs are part of the promise the UI makes in the script viewer,
    // so they are exported rather than re-typed in the frontend.
    out.push_str("export const COMMANDS: Readonly<Record<ActionId, readonly string[]>> = {\n");
    for def in manifest::ACTIONS {
        let args = match def.command {
            CommandSpec::None => Vec::new(),
            CommandSpec::Fixed { program, args } => {
                let mut all = vec![program.to_string()];
                all.extend(args.iter().map(|arg| arg.to_string()));
                all
            }
        };
        let rendered = args
            .iter()
            .map(|arg| format!("'{}'", escape(arg)))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("  '{}': [{rendered}],\n", def.id.as_str()));
    }
    out.push_str("};\n\n");

    out.push_str("export const SCAFFOLD_MARKER = 'zenith-catalog-v1';\n\n");

    // The fast-diagnose threshold is a manifest fact, not a renderer constant.
    // `actions.ts` used to hard-code `3000` while the core filtered on its own
    // copy, so the progress total the UI showed could disagree with the probes
    // the core actually ran (DEF-093). Emitting it here keeps one number.
    out.push_str(&format!(
        "export const FAST_DIAGNOSE_BUDGET_MS = {};\n",
        manifest::FAST_DIAGNOSE_BUDGET_MS
    ));

    // A silent generator that wrote nothing would look like success.
    assert!(
        manifest::ACTIONS.len() == 22,
        "manifest changed size; regenerate the UI copy deliberately"
    );
    // A scope of `none` is not a claim about mutation: `unlock-dev-ports` has no
    // filesystem or registry scope because it operates on PIDs, not paths. What
    // must hold is that a scope-less action never declares a disposable scope.
    assert!(
        !manifest::ACTIONS
            .iter()
            .any(|def| def.scope == ActionScope::None && manifest::is_disposable_scope(def.scope)),
        "disposable scopes must be real scopes"
    );

    out
}

/// Render a snippet as a JavaScript string literal.
///
/// Byte-for-byte JSON string syntax, hand-rolled so this module stays
/// dependency-free. `serde_json` would work, but its version of this function
/// returns a `Result` the caller cannot meaningfully handle: a `&str` always
/// serialises.
///
/// U+2028/U+2029 are escaped because they were line terminators inside string
/// literals before ES2019; emitting them raw would break an older WebView.
fn template(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for character in text.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            control if (control as u32) < 0x20 => {
                out.push_str(&format!("\\u{:04x}", control as u32));
            }
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

fn escape(text: &str) -> String {
    text.replace('\\', "\\\\").replace('\'', "\\'")
}
