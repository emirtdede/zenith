/// Look up by id. Linear scan over 22 entries is faster than a map and keeps
/// the table `const`.
///
/// # Panics
///
/// Never, in a correct build. The `ActionId` enum and [`ACTIONS`] are both
/// edited in the same commit, and `tests::every_code_row_matches_the_table`
/// proves the table covers every variant. Returning `Option` instead would push
/// an impossible branch onto 22 call sites, so the invariant is asserted once
/// here and enforced by that test.
#[allow(clippy::expect_used)]
pub fn action_by_id(id: ActionId) -> &'static ActionDef {
    ACTIONS
        .iter()
        .find(|def| def.id == id)
        .expect("every ActionId variant has a manifest row")
}

/// Ids that require elevation.
pub fn admin_action_ids() -> impl Iterator<Item = ActionId> {
    ACTIONS.iter().filter(|d| d.requires_admin).map(|d| d.id)
}

/// Probes at or under this budget run in a "fast" pass (`03-04` §5.3).
///
/// This is the single source of the number. It used to be typed twice - as
/// `FAST_DIAGNOSE_BUDGET_MS` in the shell and as a bare `3000` in
/// `src/actions.ts` - so the renderer's progress total and the core's actual
/// selection could disagree the moment a manifest budget moved. The generated
/// catalogue now carries this value, and the shell reads it from there.
pub const FAST_DIAGNOSE_BUDGET_MS: u64 = 3_000;

/// The safe preset, in the exact order the UI presents it.
///
/// This is an explicit list rather than "every eligible row sorted by
/// `order`" on purpose: the preset is a *user journey* (cheap network probes
/// first, slow repairs last), not a filtered table. Deriving it would silently
/// reorder the journey whenever a manifest row moved. `verify()` proves every
/// member is still eligible, so the two can never drift apart.
pub const SAFE_PRESET: [ActionId; 8] = [
    FlushDnsCache,
    CleanTempCache,
    ClearStuckProxyVpn,
    WindowsUpdateScan,
    SyncNtpTime,
    RestartBluetooth,
    ResetPrintSpooler,
    ArchiveScreenshots,
];

/// Members of the safe preset, in presentation order.
pub fn safe_preset() -> Vec<&'static ActionDef> {
    SAFE_PRESET.iter().map(|id| action_by_id(*id)).collect()
}

/// Scopes whose contents are disposable by definition, so deleting from them
/// is reversible *in the only sense that matters to the user*: nothing of value
/// is lost. This is what lets an irreversible tier still be batch-eligible
/// (ADR-007, `03-05` §4).
pub const fn is_disposable_scope(scope: ActionScope) -> bool {
    matches!(scope, ActionScope::TempDirs)
}

/// The exact predicate the batch validator and script exporter both use.
///
/// Two gates are deliberately kept apart, because conflating them was the
/// v1.0.0 defect that made the safe preset impossible to satisfy:
///
/// * **Batch eligibility** (this function) - "may run unattended, in sequence,
///   without a per-step confirmation prompt". Depends on risk, abortability and
///   whether the scope is disposable. It does *not* depend on `requires_admin`:
///   an elevated step joins the batch and the runner either elevates once up
///   front or reports it as skipped (REQ-F-028 / `plan_batch`).
/// * **Confirmation** - "does the user have to acknowledge that this cannot be
///   undone" (`executor::validate_execution`). Driven by `tier`.
///
/// An irreversible action is therefore batchable when it mutates nothing
/// (`no_mutation`) or when everything it mutates is disposable.
pub fn is_batch_eligible(def: &ActionDef) -> bool {
    if def.risk == Risk::Destructive || def.abortable || def.read_only {
        return false;
    }
    if !def.safe_batch {
        return false;
    }
    if def.tier == ReversibilityTier::Irreversible && !def.no_mutation {
        // Permanent deletion is only batch-safe where the scope is disposable.
        return is_disposable_scope(def.scope);
    }
    true
}

/// Structural verification. Returns every violation rather than the first, so a
/// broken manifest produces one useful message instead of a scavenger hunt.
pub fn verify() -> Vec<String> {
    let mut problems = Vec::new();

    if ACTIONS.len() != 22 {
        problems.push(format!("expected 22 actions, found {}", ACTIONS.len()));
    }

    let mut seen_ids = std::collections::HashSet::new();
    let mut seen_orders = std::collections::HashSet::new();
    for def in ACTIONS {
        if !seen_ids.insert(def.id) {
            problems.push(format!("duplicate id {}", def.id));
        }
        if !seen_orders.insert(def.order) {
            problems.push(format!("duplicate order {} ({})", def.order, def.id));
        }
        let id = def.id.as_str();
        let kebab = !id.is_empty()
            && id.split('-').all(|part| {
                !part.is_empty()
                    && part
                        .chars()
                        .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
            });
        if !kebab {
            problems.push(format!("id is not kebab-case: {id}"));
        }
        // Elevation is a *run-time* gate (`plan_batch` + the UAC handover), not
        // an eligibility gate: an elevated step may sit in a batch and be
        // skipped or elevated as a group. Requiring `!requires_admin` here is
        // what made the documented safe preset impossible to satisfy.
        if def.risk == Risk::Destructive && def.safe_batch {
            problems.push(format!("{} is destructive yet batchable", def.id));
        }
        if def.safe_batch && def.abortable {
            problems.push(format!("{} is abortable so must not be batchable", def.id));
        }
        if def.read_only && def.safe_batch {
            problems.push(format!(
                "{} is read-only so it must not be batchable",
                def.id
            ));
        }
        if def.read_only && !def.no_mutation {
            problems.push(format!("{} is read-only but claims to mutate", def.id));
        }
        if def.tier == ReversibilityTier::Irreversible
            && def.safe_batch
            && !def.no_mutation
            && !is_disposable_scope(def.scope)
        {
            problems.push(format!(
                "{} is irreversible and mutates durable state, so it must not be batchable",
                def.id
            ));
        }
        if def.ps1.trim().is_empty() {
            problems.push(format!("{} has an empty PowerShell snippet", def.id));
        }
        if def.bat.trim().is_empty() {
            problems.push(format!("{} has an empty batch snippet", def.id));
        }
        if def.ps1.contains("{") && def.ps1.contains("TODO") {
            problems.push(format!("{} has an unfilled snippet placeholder", def.id));
        }
        if def.timeout_secs == 0 {
            problems.push(format!("{} has no timeout", def.id));
        }
        if !(1..=3).contains(&def.severity_weight) {
            problems.push(format!("{} has severity_weight outside 1..=3", def.id));
        }
        for dep in def.depends_on {
            if !ACTIONS.iter().any(|candidate| candidate.id == *dep) {
                problems.push(format!("{} depends on unknown {}", def.id, dep));
            }
            if *dep == def.id {
                problems.push(format!("{} depends on itself", def.id));
            }
        }
    }

    let mut orders: Vec<u8> = ACTIONS.iter().map(|d| d.order).collect();
    orders.sort_unstable();
    for (index, order) in orders.iter().enumerate() {
        if *order as usize != index + 1 {
            problems.push(format!("order sequence is not 1..=22 at position {index}"));
            break;
        }
    }

    // Cycle detection over the whole dependency graph.
    let all_ids: Vec<ActionId> = ACTIONS.iter().map(|d| d.id).collect();
    if let Err(cycle) = crate::engine::dag::topological_order(&all_ids) {
        problems.push(cycle.to_string());
    }

    // The safe preset is hand-written (it is a user journey, not a filter), so
    // it is validated here instead of being derived. Every member must still be
    // eligible, non-destructive and free of elevation *or* explicitly allowed
    // to elevate as a group; and the eight steps must not appear twice.
    if SAFE_PRESET.len() != 8 {
        problems.push(format!(
            "safe preset must have exactly 8 steps, found {}",
            SAFE_PRESET.len()
        ));
    }
    let mut seen_preset = std::collections::HashSet::new();
    for id in SAFE_PRESET {
        if !seen_preset.insert(id) {
            problems.push(format!("safe preset lists {id} twice"));
        }
        let def = action_by_id(id);
        if def.risk == Risk::Destructive {
            problems.push(format!("safe preset contains destructive {id}"));
        }
        if def.abortable {
            problems.push(format!("safe preset contains abortable {id}"));
        }
        if def.read_only {
            problems.push(format!("safe preset contains read-only {id}"));
        }
        if !is_batch_eligible(def) {
            problems.push(format!("safe preset contains ineligible {id}"));
        }
    }

    // Batch eligibility must never disagree with the per-row flags: the preset,
    // the batch validator and the script exporter all call this one predicate.
    for def in ACTIONS {
        if is_batch_eligible(def) && (!def.safe_batch || def.abortable) {
            problems.push(format!(
                "{} is eligible yet not safe_batch or abortable",
                def.id
            ));
        }
    }

    problems
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_is_structurally_sound() {
        let problems = verify();
        assert!(problems.is_empty(), "manifest problems: {problems:#?}");
    }

    #[test]
    fn exactly_twenty_two_actions() {
        assert_eq!(ACTIONS.len(), 22);
    }

    #[test]
    fn every_code_row_matches_the_table() {
        // Guards the classic drift: a variant added to the enum but not the table.
        let ids: std::collections::HashSet<_> = ACTIONS.iter().map(|d| d.id).collect();
        assert_eq!(ids.len(), 22);
        for def in ACTIONS {
            assert_eq!(action_by_id(def.id).id, def.id);
        }
    }

    #[test]
    fn safe_preset_is_eight_ordered_eligible_steps() {
        let preset = safe_preset();
        assert_eq!(preset.len(), 8);
        assert_eq!(
            preset.iter().map(|d| d.id).collect::<Vec<_>>(),
            SAFE_PRESET.to_vec()
        );
        for def in preset {
            assert_ne!(def.risk, Risk::Destructive, "{}", def.id);
            assert!(!def.abortable, "{}", def.id);
            assert!(!def.read_only, "{}", def.id);
            assert!(is_batch_eligible(def), "{}", def.id);
        }
    }

    #[test]
    fn elevated_preset_steps_are_reported_not_hidden() {
        // Elevation is a run-time gate. A preset step that needs admin must be
        // accepted by `plan_batch` when elevated and skipped *by name* when not,
        // never silently dropped and never an eligibility failure.
        let elevated: Vec<ActionId> = safe_preset()
            .iter()
            .filter(|d| d.requires_admin)
            .map(|d| d.id)
            .collect();
        assert!(
            !elevated.is_empty(),
            "the preset is documented to include elevated steps"
        );

        let plan = crate::engine::executor::plan_batch(&SAFE_PRESET, false).expect("plan");
        for id in &elevated {
            assert!(
                plan.skipped
                    .iter()
                    .any(|(skipped, reason)| skipped == id && reason == "elevation_required"),
                "{id} was not reported as elevation_required"
            );
            assert!(!plan.steps.contains(id), "{id} ran without elevation");
        }
    }

    #[test]
    fn irreversible_mutating_actions_are_only_batchable_in_disposable_scopes() {
        for def in ACTIONS {
            if def.tier == ReversibilityTier::Irreversible && !def.no_mutation {
                if is_disposable_scope(def.scope) {
                    // Deleting stale temp files loses nothing recoverable.
                    assert!(def.safe_batch, "{} is disposable but not batchable", def.id);
                } else {
                    assert!(
                        !def.safe_batch,
                        "{} destroys durable state yet claims to be batchable",
                        def.id
                    );
                }
            }
        }
    }

    #[test]
    fn reboot_is_destructive_abortable_and_never_batchable() {
        let def = action_by_id(ControlledReboot);
        assert_eq!(def.risk, Risk::Destructive);
        assert!(def.abortable);
        assert!(!def.safe_batch);
        assert!(!is_batch_eligible(def));
    }

    #[test]
    fn windows_update_scan_does_not_need_admin() {
        // v1.0.0 wrongly required elevation here, which produced a false lock
        // badge and broke the safe preset.
        assert!(!action_by_id(WindowsUpdateScan).requires_admin);
        assert!(action_by_id(WindowsUpdateScan).no_mutation);
    }

    #[test]
    fn sfc_depends_on_dism() {
        assert!(
            action_by_id(SfcSystemScan)
                .depends_on
                .contains(&DismRestoreHealth)
        );
    }

    #[test]
    fn scope_of_every_action_is_declared() {
        for def in ACTIONS {
            assert!(!def.scope.as_str().is_empty(), "{}", def.id);
        }
    }

    #[test]
    fn no_snippet_contains_a_todo_marker() {
        for def in ACTIONS {
            let haystack = format!("{}\n{}", def.ps1, def.bat).to_lowercase();
            assert!(!haystack.contains("todo"), "{}", def.id);
            assert!(!haystack.contains("<placeholder>"), "{}", def.id);
        }
    }
}
