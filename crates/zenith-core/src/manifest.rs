//! The action manifest: one table, twenty-two rows, no duplication.
//!
//! Historically these facts lived in six places (Rust enum, TS catalog, locale
//! files, a prose table, script snippets, inline risk flags), so they drifted.
//! Here they live once. `manifest::verify()` enforces the invariants at test
//! time, and the TypeScript side is generated from the same data shape.
//!
//! Invariants (each has a test):
//!
//! * ids are unique, kebab-case, and contiguous by `order` from 1
//! * `safe_batch` implies safe, non-destructive, non-elevated, non-blocking
//! * `destructive` is never batchable
//! * `depends_on` is acyclic and references real ids
//! * every action has a scope, a timeout, a diagnose budget and both snippets
//! * `irreversible` never claims rollback

use crate::models::{ActionId, ReversibilityTier, Risk};

/// A rollback scope. Rollback targets resolve through this allowlist; a stored
/// free-form path is never trusted (ADR-007).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActionScope {
    TempDirs,
    RecycleBin,
    Screenshots,
    IconCache,
    Spooler,
    OfficeCache,
    InternetSettings,
    Winsock,
    ServicesOnly,
    ExplorerSession,
    None,
}

impl ActionScope {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::TempDirs => "temp_dirs",
            Self::RecycleBin => "recycle_bin",
            Self::Screenshots => "screenshots",
            Self::IconCache => "icon_cache",
            Self::Spooler => "spooler",
            Self::OfficeCache => "office_cache",
            Self::InternetSettings => "internet_settings",
            Self::Winsock => "winsock",
            Self::ServicesOnly => "services_only",
            Self::ExplorerSession => "explorer_session",
            Self::None => "none",
        }
    }
}

/// The shape of an action's external-program invocation, if any.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommandSpec {
    /// No child process; the action calls APIs directly.
    None,
    /// A fixed program with a fixed argument vector. Never a shell string.
    Fixed {
        program: &'static str,
        args: &'static [&'static str],
    },
}

/// One row of the manifest.
#[derive(Debug, Clone, Copy)]
pub struct ActionDef {
    pub id: ActionId,
    pub order: u8,
    pub category: Category,
    pub risk: Risk,
    pub tier: ReversibilityTier,
    pub requires_admin: bool,
    pub safe_batch: bool,
    /// Can the user stop it mid-flight (countdowns). Orthogonal to `tier`.
    pub abortable: bool,
    /// Leaves no durable state that would need a snapshot to undo.
    ///
    /// Not the same as "calls no write API". `flush-dns-cache` writes the
    /// resolver cache; `windows-update-scan` writes scan logs. Both are
    /// `true` here because the only state they touch is regenerated by Windows
    /// on the next use, so a rollback would restore nothing a user could miss.
    /// This flag is what allows an `irreversible` tier to be batch-eligible
    /// without pretending the action is reversible.
    pub no_mutation: bool,
    /// Observational only: the UI shows no run button.
    pub read_only: bool,
    pub depends_on: &'static [ActionId],
    pub timeout_secs: u64,
    pub severity_weight: u8,
    pub scope: ActionScope,
    pub diagnose_budget_ms: u64,
    pub command: CommandSpec,
    pub i18n_prefix: &'static str,
    pub ps1: &'static str,
    pub bat: &'static str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Category {
    Cleanup,
    Network,
    Recovery,
    DevOffice,
}

impl Category {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Cleanup => "cleanup",
            Self::Network => "network",
            Self::Recovery => "recovery",
            Self::DevOffice => "dev_office",
        }
    }
}

